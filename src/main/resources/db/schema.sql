-- POS 스키마 (운영 DB에서 sqlite3 .schema 로 추출, 2026-11-11)
-- 제외: sqlite_sequence(SQLite 내부 테이블), raw_product_data(이관용 원본, 코드에서 미사용)
-- 재실행해도 안전하도록 CREATE ... IF NOT EXISTS 로 변환함. 그 외 정의는 운영 DB와 동일.

CREATE TABLE IF NOT EXISTS BRAND(
    BRAND_ID INTEGER PRIMARY KEY AUTOINCREMENT,
    BRAND_NAME TEXT NOT NULL, -- 브랜드 이름
    CREATED_AT TEXT,
    UPDATED_AT TEXT
);

CREATE TABLE IF NOT EXISTS CATEGORY(
    CATEGORY_ID INTEGER PRIMARY KEY AUTOINCREMENT,
    CATEGORY_CODE TEXT NOT NULL UNIQUE, -- 카테고리 코드, 예: '001', '002' 등
    CATEGORY_NAME TEXT NOT NULL, -- 카테고리 이름
    CREATED_AT TEXT,
    UPDATED_AT TEXT
);

CREATE TABLE IF NOT EXISTS PRODUCT(
    PRODUCT_ID TEXT PRIMARY KEY,
    BARCODE TEXT NOT NULL UNIQUE,
    NAME TEXT NOT NULL,
    PRICE REAL NOT NULL,
    EXPIRY_DATE TEXT, -- 몇몇 상품은 유통기한이 없을 수 있으므로 nullable
    IS_ADULT_ONLY INTEGER, -- 성인 인증이 필요한 상품은 1, 그렇지 않은 상품은 0
    PRODUCT_STATUS TEXT, -- 상품 상태는 '판매중', '발주중단', '판매중단' 등으로 구분될 수 있음
    CREATED_AT INTEGER,
    UPDATED_AT INTEGER,
    BRAND_ID TEXT, -- 브랜드 칼럼은, 0개 이거나 1개 이상의 상품을 가질 수 있으므로 nullable 함.
    CATEGORY_ID TEXT NOT NULL,
    FOREIGN KEY (BRAND_ID) REFERENCES BRAND(BRAND_ID),
    FOREIGN KEY (CATEGORY_ID) REFERENCES CATEGORY(CATEGORY_ID)
);

CREATE TABLE IF NOT EXISTS INVENTORY (
    PRODUCT_ID TEXT PRIMARY KEY REFERENCES PRODUCT(PRODUCT_ID) ON DELETE CASCADE ON UPDATE CASCADE, -- 상품 ID, PRODUCT 테이블과 일대일 관계, 일대일 관계에서는 외례키를 더 종속적인 테이블의 연결
    STOCK INTEGER NOT NULL, -- 재고 수량
    CREATED_AT TEXT,
    UPDATED_AT TEXT
);

CREATE TABLE IF NOT EXISTS CATEGORY_BRAND(
    CATEGORY_ID INTEGER NOT NULL,
    BRAND_ID INTEGER NOT NULL,
    PRIMARY KEY (CATEGORY_ID, BRAND_ID),
    FOREIGN KEY (CATEGORY_ID) REFERENCES CATEGORY(CATEGORY_ID),
    FOREIGN KEY (BRAND_ID) REFERENCES BRAND(BRAND_ID)
);

CREATE TABLE IF NOT EXISTS SALES (
        SALE_ID       INTEGER PRIMARY KEY AUTOINCREMENT,
        RECEIPT_NO    TEXT    NOT NULL,
        STORE_CD      TEXT    NOT NULL,
        POS_NO        TEXT    NOT NULL,
        TRAN_NO       TEXT    NOT NULL,
        CASHIER       TEXT,                     -- nullable
        SALE_STATUS   TEXT    NOT NULL CHECK (SALE_STATUS IN ('NORMAL','REFUNDED')),
        APPROVED_AT   TEXT    NOT NULL,         -- ISO8601 문자열 (Instant.toString())
        TOTAL_QTY     INTEGER NOT NULL,
        TOTAL_AMOUNT  NUMERIC NOT NULL,         -- BigDecimal 대응
        ORIG_SALE_ID  INTEGER,                  -- 환불 시 원거래 참조
        UNIQUE (STORE_CD, POS_NO, TRAN_NO),
        FOREIGN KEY (ORIG_SALE_ID) REFERENCES SALES(SALE_ID)
);

CREATE TABLE IF NOT EXISTS SALE_LINES (
        SALE_LINE_ID  INTEGER PRIMARY KEY AUTOINCREMENT,
        SALE_ID       INTEGER NOT NULL,
        LINE_NO       TEXT NOT NULL,         -- 1,2,3.. (정렬/고유)
        BARCODE       TEXT    NOT NULL,
        NAME          TEXT    NOT NULL,
        UNIT_PRICE    NUMERIC NOT NULL,
        QTY           INTEGER NOT NULL,
        AMOUNT        NUMERIC NOT NULL,         -- QTY * UNIT_PRICE 스냅샷
        ITEM_STATUS   TEXT    NOT NULL CHECK (ITEM_STATUS IN ('NORMAL', 'REFUNDED', 'CANCELLED')),
        UNIQUE (SALE_ID, LINE_NO),
        FOREIGN KEY (SALE_ID) REFERENCES SALES(SALE_ID) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS PAYMENTS (
        PAYMENT_ID        INTEGER PRIMARY KEY AUTOINCREMENT,
        SALE_ID           INTEGER NOT NULL,
        METHOD            TEXT    NOT NULL CHECK (METHOD IN ('CASH','CARD','VOUCHER','POINT')),
        STATUS            TEXT    NOT NULL CHECK (STATUS IN ('APPROVED','DECLINED','VOIDED','REFUNDED')),
        AMOUNT_DUE_TO_PAY NUMERIC NOT NULL,     -- 수단별 청구액(=실 지불액)
        APPROVED_AT       TEXT    NOT NULL,
        FOREIGN KEY (SALE_ID) REFERENCES SALES(SALE_ID) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS RECEIPT_JOURNAL (
    JOURNAL_ID   INTEGER PRIMARY KEY AUTOINCREMENT,

    -- 조회 키(정규 테이블과 연결)
    SALE_ID      INTEGER NOT NULL,
    RECEIPT_NO   TEXT    NOT NULL,
    STORE_CD     TEXT    NOT NULL,
    POS_NO       TEXT    NOT NULL,
    TRAN_NO      TEXT    NOT NULL,
    APPROVED_AT  TEXT    NOT NULL,     -- ISO8601 (= SALES.APPROVED_AT 그대로)

    -- 스냅샷(거래 원문 TR JSON)
    TR_JSON      TEXT    NOT NULL,     -- 네 예시 JSON 그대로 저장
    BODY_TEXT    TEXT,                 -- 텍스트 영수증(렌더 결과가 있으면)

    FOREIGN KEY (SALE_ID) REFERENCES SALES(SALE_ID) ON DELETE CASCADE,

    UNIQUE (SALE_ID)
);

CREATE TABLE IF NOT EXISTS CASH_PAYMENTS (
        PAYMENT_ID      INTEGER PRIMARY KEY AUTOINCREMENT,
        AMOUNT_RECEIVED NUMERIC NOT NULL,
        CHANGE          NUMERIC NOT NULL,
        FOREIGN KEY (PAYMENT_ID) REFERENCES PAYMENTS(PAYMENT_ID) ON DELETE CASCADE
);

CREATE INDEX IF NOT EXISTS idx_brand_name ON BRAND (BRAND_NAME);

CREATE INDEX IF NOT EXISTS idx_category_code ON CATEGORY (CATEGORY_CODE);

CREATE INDEX IF NOT EXISTS idx_product_id ON PRODUCT (PRODUCT_ID);

CREATE INDEX IF NOT EXISTS idx_product_barcode on product (barcode);
